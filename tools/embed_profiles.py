#!/usr/bin/env python3
"""Regenerates OBDKit/Sources/OBDKit/Catalog/BuiltInProfiles.swift from profiles/*.json.

The app embeds the profiles as string literals so the package needs no resource bundle.
A unit test fails if the two drift apart.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "OBDKit/Sources/OBDKit/Catalog/BuiltInProfiles.swift"

parts = ["// Generated by tools/embed_profiles.py from profiles/*.json. Don't edit by hand.\n",
         "import Foundation\n\n",
         "public enum BuiltInProfiles {\n",
         "    public static let all: [VehicleProfile] = sources.compactMap { try? VehicleProfile.decode(Data($0.utf8)) }\n\n",
         "    public static func profile(id: String) -> VehicleProfile? { all.first { $0.id == id } }\n\n",
         "    static let sources: [String] = [\n"]
for path in sorted((ROOT / "profiles").glob("*.json")):
    text = json.dumps(json.loads(path.read_text(encoding="utf-8")), ensure_ascii=False, indent=1)
    assert '"""' not in text
    parts.append('        #"""\n' + text + '\n"""#,\n')
parts.append("    ]\n}\n")
OUT.write_bytes("".join(parts).encode("utf-8"))
print(f"wrote {OUT.relative_to(ROOT)}")
